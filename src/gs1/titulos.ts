const MEDIDA: Record<string, string> = {
  "NET WEIGHT": "Peso líquido",
  "GROSS WEIGHT": "Peso bruto",
  LENGTH: "Comprimento",
  WIDTH: "Largura",
  HEIGHT: "Altura",
  AREA: "Área",
  "NET VOLUME": "Volume líquido",
  VOLUME: "Volume",
};

export function tituloPt(oficial: string): string {
  if (EXATOS[oficial]) return EXATOS[oficial];
  const nhrn = /^NHRN ([A-Z]+)$/.exec(oficial);
  if (nhrn) return `NHRN ${nhrn[1]}`;
  const cert = /^CERT # (\d+)$/.exec(oficial);
  if (cert) return `Certificado nº ${cert[1]}`;
  const proc = /^PROCESSOR # (\d+)$/.exec(oficial);
  if (proc) return `Processador nº ${proc[1]}`;
  const medida = /^(NET WEIGHT|GROSS WEIGHT|LENGTH|WIDTH|HEIGHT|AREA|NET VOLUME|VOLUME) \((.+)\)(?:, log)?$/.exec(
    oficial,
  );
  if (medida) {
    const logistico = oficial.endsWith(", log") ? ", logístico" : "";
    return `${MEDIDA[medida[1]]} (${medida[2]})${logistico}`;
  }
  const ship = /^SHIP TO (.+)$/.exec(oficial);
  if (ship) return `Destinatário — ${DESTINO[ship[1]] ?? ship[1]}`;
  const rtn = /^RTN TO (.+)$/.exec(oficial);
  if (rtn) return `Devolução — ${DESTINO[rtn[1]] ?? rtn[1]}`;
  return oficial;
}
